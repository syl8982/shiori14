/**
 * 아카이브·작가노트 원본 → 웹용 WebP 생성 + 갤러리 manifest 갱신
 * 원본(public/images/archive, notes)은 수정하지 않음.
 *
 * Usage: node scripts/generate-gallery-web-images.mjs
 */

import { mkdir, readdir, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const PUBLIC = path.join(ROOT, 'public', 'images')

const MAX_LONG_EDGE = 1800
const TARGET_MAX_BYTES = 1_000_000
const MIN_QUALITY = 70
const START_QUALITY = 82

const IMAGE_EXT = /\.(jpe?g|png|gif|webp)$/i

async function ensureDir(dir) {
  await mkdir(dir, { recursive: true })
}

async function listImages(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  return entries
    .filter((entry) => entry.isFile() && IMAGE_EXT.test(entry.name))
    .map((entry) => path.join(dir, entry.name))
    .sort((a, b) => path.basename(a).localeCompare(path.basename(b), 'ko'))
}

async function encodeWebImage(srcPath, destPath) {
  const rotatedMeta = await sharp(srcPath).rotate().metadata()

  let quality = START_QUALITY
  let lastSize = Infinity

  while (quality >= MIN_QUALITY) {
    let pipeline = sharp(srcPath).rotate()
    const longEdge = Math.max(rotatedMeta.width, rotatedMeta.height)

    if (longEdge > MAX_LONG_EDGE) {
      pipeline =
        rotatedMeta.width >= rotatedMeta.height
          ? pipeline.resize(MAX_LONG_EDGE, null, { withoutEnlargement: true })
          : pipeline.resize(null, MAX_LONG_EDGE, { withoutEnlargement: true })
    }

    await pipeline.webp({ quality, effort: 4 }).toFile(destPath)
    const { size } = await stat(destPath)
    lastSize = size

    if (size <= TARGET_MAX_BYTES) {
      break
    }

    quality -= 4
  }

  const outputMeta = await sharp(destPath).metadata()
  return {
    aspectRatio: outputMeta.height / outputMeta.width,
    size: lastSize,
    quality,
  }
}

function toPublicPath(absolutePath) {
  const relative = path.relative(path.join(ROOT, 'public'), absolutePath).split(path.sep).join('/')
  return `/${relative}`
}

function manifestEntry(name, webAbsPath, aspectRatio) {
  return {
    name,
    src: toPublicPath(webAbsPath),
    aspectRatio: +aspectRatio.toFixed(6),
  }
}

async function processFolder({ sourceDir, webDir, label }) {
  await ensureDir(webDir)
  const sources = await listImages(sourceDir)
  const entries = []

  for (const srcPath of sources) {
    const base = path.basename(srcPath, path.extname(srcPath))
    const destPath = path.join(webDir, `${base}.webp`)
    const { aspectRatio, size } = await encodeWebImage(srcPath, destPath)
    entries.push(manifestEntry(path.basename(srcPath), destPath, aspectRatio))
    console.log(`[${label}] ${path.basename(srcPath)} → ${path.basename(destPath)} (${Math.round(size / 1024)}KB, ratio ${aspectRatio.toFixed(3)})`)
  }

  return entries
}

function renderManifest(moduleName, exportName, entries) {
  const body = entries
    .map(
      (entry) =>
        `  { name: ${JSON.stringify(entry.name)}, src: ${JSON.stringify(entry.src)}, aspectRatio: ${entry.aspectRatio} },`,
    )
    .join('\n')

  return `/** Auto-generated by scripts/generate-gallery-web-images.mjs — do not edit manually */

export const ${exportName} = [
${body}
]
`
}

async function main() {
  const archiveEntries = await processFolder({
    sourceDir: path.join(PUBLIC, 'archive'),
    webDir: path.join(PUBLIC, 'archive-web'),
    label: 'archive',
  })

  const notes1Entries = await processFolder({
    sourceDir: path.join(PUBLIC, 'notes', 'notes1'),
    webDir: path.join(PUBLIC, 'notes-web', 'notes1'),
    label: 'notes1',
  })

  const notesRootEntries = await processFolder({
    sourceDir: path.join(PUBLIC, 'notes'),
    webDir: path.join(PUBLIC, 'notes-web'),
    label: 'notes-root',
  })

  const noteEntries = [...notes1Entries, ...notesRootEntries]

  const dataDir = path.join(ROOT, 'src', 'data')
  await ensureDir(dataDir)

  await writeFile(
    path.join(dataDir, 'archiveGalleryEntries.js'),
    renderManifest('archiveGalleryEntries', 'ARCHIVE_GALLERY_ENTRIES', archiveEntries),
    'utf8',
  )

  await writeFile(
    path.join(dataDir, 'noteGalleryEntries.js'),
    renderManifest('noteGalleryEntries', 'NOTE_GALLERY_ENTRIES', noteEntries),
    'utf8',
  )

  const archiveTotal = archiveEntries.length
  const noteTotal = noteEntries.length
  console.log(`\nDone: ${archiveTotal} archive + ${noteTotal} note web images.`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
